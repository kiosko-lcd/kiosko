"""Writes main/font.h: DejaVu Sans Bold glyphs with 4-bit antialiasing.

Usage (Docker, nothing installed on the host): tools/gen_font.sh
"""
from PIL import Image, ImageDraw, ImageFont

CHARS = [chr(c) for c in range(32, 127)] + list("áéíóúÁÉÍÓÚñÑüÜäöÄÖß¿¡·…°")
SIZES = {"tiny": 12, "small": 16, "big": 26}
PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

out = ["// Generated by tools/gen_font.py (DejaVu Sans Bold, 4-bit antialiasing); do not edit.", "#pragma once", "#include <stdint.h>", "",
       "typedef struct { uint32_t cp; uint8_t w, adv; uint32_t off; } glyph_t;",
       "typedef struct { uint8_t h; uint16_t n; const glyph_t *g; const uint8_t *bits; } font_t;", ""]
for name, size in SIZES.items():
    f = ImageFont.truetype(PATH, size)
    asc, desc = f.getmetrics()
    h = asc + desc
    glyphs, bits = [], bytearray()
    for ch in CHARS:
        adv = round(f.getlength(ch))
        l, _, r, _ = f.getbbox(ch)
        w = max(r, adv, 1)
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255)
        px = im.load()
        off = len(bits)
        for y in range(h):          # 4 bits a pixel, two pixels a byte, rows byte-aligned
            for x in range(0, w, 2):
                a = px[x, y] >> 4
                b = (px[x + 1, y] >> 4) if x + 1 < w else 0
                bits.append((a << 4) | b)
        glyphs.append((ord(ch), w, adv, off))
    out.append(f"static const uint8_t font_{name}_bits[] = {{")
    for i in range(0, len(bits), 24):
        out.append("    " + ",".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const glyph_t font_{name}_glyphs[] = {{")
    for cp, w, adv, off in glyphs:
        out.append(f"    {{0x{cp:04x}, {w}, {adv}, {off}}},")
    out.append("};")
    out.append(f"static const font_t font_{name} = {{ {h}, {len(glyphs)}, font_{name}_glyphs, font_{name}_bits }};")
    out.append("")
print("\n".join(out))
