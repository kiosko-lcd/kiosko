/**
 * Test vectors shared with the firmware: `firmware/esp32-screen/test/vectors.h`
 * is this output, and the firmware's host test (test/run.sh) checks
 * ks_proto.c against it. vectors.test.ts fails when they drift apart;
 * `UPDATE_VECTORS=1 npm test` rewrites the header.
 */
import { createHash } from 'node:crypto';
import { LABEL_AUTH_D, LABEL_AUTH_K, SpakeA, authMac, seal, sessionKeys, spakeRespond, spakeW } from './crypto.ts';
import { scalarBytes } from './p256.ts';

const fixed = (label: string) => createHash('sha256').update(label).digest();

export function vectors(): Record<string, string> {
  const uid = 'a085e3ae92d0';
  const code = '073519';
  const x = BigInt('0x' + fixed('kiosko vector x').toString('hex')) % 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551n;
  const y = BigInt('0x' + fixed('kiosko vector y').toString('hex')) % 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551n;
  const a = new SpakeA(uid, code, x);
  const b = spakeRespond(uid, code, a.X, y);
  const ka = a.finish(b.Y);
  if (!ka.key.equals(b.key)) throw new Error('SPAKE2 halves disagree');
  const key = b.key;
  const nk = fixed('kiosko vector nk'), nd = fixed('kiosko vector nd');
  const s = sessionKeys(key, nk, nd, 'kiosko');
  const m0 = seal(s.tx, 0x15, Buffer.from('{}'));
  const m1 = seal(s.tx, 0x10, Buffer.concat([Buffer.from([0, 0, 0, 7]), Buffer.from('not really a jpeg')]));
  const r0 = seal(s.rx, 0x13, Buffer.from('{"id":"desk"}')); // as the screen would seal it, with its tx key
  return {
    UID: uid,
    CODE: code,
    W: scalarBytes(spakeW(uid, code)).toString('hex'),
    Y_SCALAR: scalarBytes(y).toString('hex'),
    X: a.X.toString('hex'),
    Y: b.Y.toString('hex'),
    CA: b.cA.toString('hex'),
    CB: b.cB.toString('hex'),
    PAIR_KEY: key.toString('hex'),
    NK: nk.toString('hex'),
    ND: nd.toString('hex'),
    AUTH_K: authMac(key, LABEL_AUTH_K, nk, nd, uid).toString('hex'),
    AUTH_D: authMac(key, LABEL_AUTH_D, nk, nd, uid).toString('hex'),
    K2D_0: m0.toString('hex'),
    K2D_1: m1.toString('hex'),
    D2K_0: r0.toString('hex'),
  };
}

export function vectorsHeader(v = vectors()): string {
  const lines = Object.entries(v).map(([k, val]) => `#define V_${k} "${val}"`);
  return `// Generated by packages/core/src/remote/vectors.ts (UPDATE_VECTORS=1 npm test); do not edit.\n#pragma once\n${lines.join('\n')}\n`;
}
